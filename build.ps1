<#
.SYNOPSIS
  Builds Plugin_ModKit.dll (32-bit) from src/core.c plus every src/mod_*.c / mod_*.cpp present.

.DESCRIPTION
  Each mod registers itself with MK_MODULE(name); this script scans for those lines and
  generates build/registry.c, so every mod branch builds with only its own mods and main
  builds them all. C++ mods (the ImGui menu) need Dear ImGui: run scripts/fetch-imgui.ps1.

.PARAMETER Zig
  Path to zig.exe (0.13). Default: $env:ZIG, then zig on PATH, then C:\Users\<you>\tools\zig\zig.exe.
#>
param(
    [string]$Zig = $env:ZIG,
    [switch]$SelfTest
)
$ErrorActionPreference = 'Continue'  # native tools write warnings to stderr; failures are checked via exit codes
$root = $PSScriptRoot
$src = Join-Path $root 'src'
$out = Join-Path $root 'build'
$imgui = Join-Path $root 'third_party\imgui-1.91.9'
New-Item -ItemType Directory -Force $out | Out-Null

if (-not $Zig) {
    $cmd = Get-Command zig -ErrorAction SilentlyContinue
    if ($cmd) { $Zig = $cmd.Source } else { $Zig = Join-Path $env:USERPROFILE 'tools\zig\zig.exe' }
}
if (-not (Test-Path $Zig)) { throw "zig.exe not found ($Zig). Install Zig 0.13 or pass -Zig." }

# ---- module registry
$mods = Get-ChildItem $src -File | Where-Object { $_.Name -match '^mod_.*\.(c|cpp)$' } | Sort-Object Name
$names = foreach ($m in $mods) {
    foreach ($line in Get-Content $m.FullName) {
        if ($line -match '^\s*(?:extern\s+"C"\s+)?MK_MODULE\((\w+)\)') { $Matches[1] }
    }
}
$reg = @('/* generated by build.ps1 - do not edit */', '#include "modkit.h"')
foreach ($n in $names) { $reg += "extern Module $n;" }
if ($names) {
    $reg += 'Module *mk_registry[] = { ' + (($names | ForEach-Object { "&$_" }) -join ', ') + ' };'
} else {
    $reg += 'Module *mk_registry[1];'
}
$reg += "int mk_registry_count = $(@($names).Count);"
$reg -join "`n" | Set-Content -Encoding ascii (Join-Path $out 'registry.c')
Write-Host "mods: $(if ($names) { $names -join ', ' } else { '(none, core only)' })"

# ---- compile
$common = @('-target', 'x86-windows-gnu', '-O2', '-Wall', '-Wextra', '-Wno-missing-field-initializers', "-I$src")
$objs = @()
$cfiles = @((Join-Path $src 'core.c'), (Join-Path $out 'registry.c')) + @($mods | Where-Object Extension -eq '.c' | ForEach-Object FullName)
$cppfiles = @($mods | Where-Object Extension -eq '.cpp' | ForEach-Object FullName)

foreach ($f in $cfiles) {
    $o = Join-Path $out ([IO.Path]::GetFileNameWithoutExtension($f) + '.o')
    & $Zig cc @common -std=c11 -c $f -o $o
    if ($LASTEXITCODE) { throw "compile failed: $f" }
    $objs += $o
}
$libs = @('-luser32', '-lkernel32')
if ($cppfiles) {
    if (-not (Test-Path (Join-Path $imgui 'imgui.h'))) { throw "Dear ImGui missing: run scripts/fetch-imgui.ps1" }
    $cpp = @('-fno-exceptions', '-fno-rtti', "-I$imgui", "-I$imgui\backends", '-DIMGUI_DISABLE_OBSOLETE_FUNCTIONS')
    $imfiles = @('imgui.cpp', 'imgui_draw.cpp', 'imgui_tables.cpp', 'imgui_widgets.cpp') | ForEach-Object { Join-Path $imgui $_ }
    $imfiles += Join-Path $imgui 'backends\imgui_impl_dx9.cpp'
    $imfiles += Join-Path $imgui 'backends\imgui_impl_win32.cpp'
    foreach ($f in $imfiles) {
        $o = Join-Path $out ('imgui_' + [IO.Path]::GetFileNameWithoutExtension($f) + '.o')
        if (-not (Test-Path $o) -or (Get-Item $o).LastWriteTime -lt (Get-Item $f).LastWriteTime) {
            & $Zig c++ -target x86-windows-gnu -O2 @cpp -c $f -o $o
            if ($LASTEXITCODE) { throw "compile failed: $f" }
        }
        $objs += $o
    }
    foreach ($f in $cppfiles) {
        $o = Join-Path $out ([IO.Path]::GetFileNameWithoutExtension($f) + '.o')
        & $Zig c++ @common @cpp -c $f -o $o
        if ($LASTEXITCODE) { throw "compile failed: $f" }
        $objs += $o
    }
    $libs += @('-lgdi32', '-limm32', '-ldwmapi')
    $linker = 'c++'
} else {
    $linker = 'cc'
}
$dll = Join-Path $out 'Plugin_ModKit.dll'
& $Zig $linker -target x86-windows-gnu -shared -o $dll @objs @libs
if ($LASTEXITCODE) { throw 'link failed' }
Write-Host "built $dll ($([math]::Round((Get-Item $dll).Length / 1KB)) KB)"

# ---- offline self-test: load the DLL in a 32-bit process and list its modules
if ($SelfTest) {
    $exe = Join-Path $out 'selftest.exe'
    & $Zig cc -target x86-windows-gnu -O1 -o $exe (Join-Path $root 'tools\selftest.c')
    if ($LASTEXITCODE) { throw 'selftest build failed' }
    & $exe $dll
    if ($LASTEXITCODE) { throw "selftest failed ($LASTEXITCODE)" }
    # offline unit tests of the mods present: tools/test_<mod file name>.c
    foreach ($m in $mods) {
        $t = Join-Path $root "tools	est_$($m.BaseName).c"
        if (-not (Test-Path $t)) { continue }
        $texe = Join-Path $out "test_$($m.BaseName).exe"
        & $Zig cc -target x86-windows-gnu -O1 "-I$src" -Wno-unused-function -o $texe $t
        if ($LASTEXITCODE) { throw "test build failed: $t" }
        & $texe | Select-Object -Last 1
        if ($LASTEXITCODE) { throw "test failed: $t" }
    }
}
